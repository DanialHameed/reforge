@router.get("/status")
async def status_summary(
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict[str, Any]:
    """
    Return real connection status for supported platforms by reading
    `social_accounts` (encrypted token store used by publishers).
    """
    tiers: dict[str, AutomationTier] = {
        "youtube": "full_auto",
        "instagram": "full_auto",
        "facebook": "full_auto",
        "x": "full_auto",
        "linkedin": "full_auto",
    }

    rows = (
        await db.execute(select(SocialAccount).where(SocialAccount.user_id == user.id))
    ).scalars().all()
    by_platform: dict[str, SocialAccount] = {}
    for a in rows:
        by_platform[(a.platform or "").lower()] = a

    platforms: list[dict[str, Any]] = []
    for ui_key in ["youtube", "instagram", "facebook", "x", "linkedin"]:
        backend_key = _normalize(ui_key)
        a = by_platform.get(backend_key)
        access = try_decrypt_token(a.access_token_encrypted) if a else None
        refresh = try_decrypt_token(a.refresh_token_encrypted) if a else None
        connected = bool(a and a.is_active and (access or refresh))
        meta = a.metadata_json if (a and isinstance(a.metadata_json, dict)) else {}
        username = (
            str(meta.get("username") or "").strip()
            or str(meta.get("name") or "").strip()
            or (str(a.platform_user_id).strip() if (a and a.platform_user_id) else "")
        )
        platforms.append(
            {
                "platform": ui_key,
                "connected": connected,
                "account": {"username": username or "connected", "profile_image_url": meta.get("profile_image_url")}
                if connected
                else None,
                "token_expires_at": a.token_expires_at.isoformat() if (a and a.token_expires_at) else None,
                "last_used_at": a.updated_at.isoformat() if (a and a.updated_at) else None,
                "tier": tiers[ui_key],
            }
        )

    return {"platforms": platforms, "evaluation_mode": settings.EVALUATION_MODE}


class ConnectResponse(BaseModel):
    auth_url: str


@router.get("/connect/{platform}", response_model=ConnectResponse)
async def connect_platform(platform: PlatformKey) -> ConnectResponse:
    """
    Tell the frontend where the OAuth start endpoint lives for this platform.

    The actual authorize URL is generated by the connections router which is the
    only place that has access to per-provider OAuth client config (PKCE, scopes,
    state signing, etc.). The frontend calls that endpoint with auth headers and
    follows the returned `authorize_url`.
    """
    p = _normalize(platform)
    path = _AUTHORIZE_PATHS.get(p)
    if not path:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, detail="Platform not supported")
    return ConnectResponse(auth_url=path)


@router.delete("/{platform}")
async def disconnect_platform(
    platform: PlatformKey,
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict[str, Any]:
    """Remove the stored OAuth tokens for this platform (social_accounts)."""
    if settings.EVALUATION_MODE:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Evaluation mode is enabled: disconnecting platforms is disabled for demo safety.",
        )

    p = _normalize(platform)
    await db.execute(
        delete(SocialAccount).where(
            SocialAccount.user_id == user.id,
            SocialAccount.platform == p,
        )
    )
    await db.commit()
    return {"ok": True}


@router.post("/{platform}/refresh")
async def refresh_platform_token(
    platform: PlatformKey,
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict[str, Any]:
    """
    Best-effort refresh. The per-platform publisher modules already refresh tokens
    automatically on demand; this endpoint exists so the user can poke a refresh
    from the Connections UI. If the platform's refresh flow isn't supported (e.g.
    Meta long-lived tokens are exchanged at OAuth time only), we just return the
    stored expiry.
    """
    p = _normalize(platform)
    sa = (
        await db.execute(select(SocialAccount).where(SocialAccount.user_id == user.id, SocialAccount.platform == p))
    ).scalar_one_or_none()
    if sa is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Platform not connected")

    # Best-effort refresh per provider.
    if p == "twitter":
        # refreshes if needed, returns access token
        pub = TwitterPublisher()
        expires = sa.token_expires_at
        if expires is not None and expires.tzinfo is None:
            expires = expires.replace(tzinfo=timezone.utc)
        if expires and expires <= datetime.now(timezone.utc):
            _ = await pub.refresh_token(sa, db)
    elif p == "linkedin":
        pub = LinkedInPublisher()
        _ = await pub._ensure_access_token(sa, db)  # noqa: SLF001 (internal helper)
    elif p == "youtube":
        pub = YouTubePublisher()
        _ = await pub._build_credentials(sa, db)  # noqa: SLF001

    return {
        "ok": True,
        "platform": p,
        "expires_at": sa.token_expires_at.isoformat() if sa.token_expires_at else None,
    }



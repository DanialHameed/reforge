class PublishAllRequest(BaseModel):
    """When captions are generic AI fallbacks, the UI must set acknowledge_placeholder_captions=true."""

    acknowledge_placeholder_captions: bool = False


@router.post("/publish-all/{content_id}")
async def publish_all(
    content_id: str,
    payload: Annotated[PublishAllRequest | None, Body()] = None,
    user: User = Depends(get_current_user),
):
    """
    Body is optional for older clients; default is no acknowledgement (generic captions stay blocked server-side).
    """
    ack = bool(payload and payload.acknowledge_placeholder_captions)
    return await publish_to_all_platforms(
        str(user.id), content_id, acknowledge_placeholder_captions=ack
    )


class PublishSelectedRequest(BaseModel):
    platforms: list[str] = Field(default_factory=list)
    acknowledge_placeholder_captions: bool = False


@router.post("/publish-selected/{content_id}")
async def publish_selected(
    content_id: str,
    payload: PublishSelectedRequest,
    user: User = Depends(get_current_user),
):
    return await publish_to_all_platforms(
        str(user.id),
        content_id,
        platforms=payload.platforms,
        acknowledge_placeholder_captions=bool(payload.acknowledge_placeholder_captions),
    )


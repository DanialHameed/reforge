async def _get_variant_for_user(variant_id: str, user_id: str, db: AsyncSession) -> PlatformVariant:
    stmt = (
        select(PlatformVariant)
        .join(ContentItem, ContentItem.id == PlatformVariant.content_item_id)
        .where(PlatformVariant.id == variant_id, ContentItem.user_id == user_id)
    )
    pv = (await db.execute(stmt)).scalar_one_or_none()
    if pv is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Platform variant not found")
    return pv


@router.post("/variants/{variant_id}/validate-media")
async def validate_variant_media(
    variant_id: str,
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
) -> dict[str, Any]:
    """
    Preflight-only media validation.

    Runs the same ffprobe-based checks as the publish worker, plus best-effort Cloudinary
    auto-fix attempt (aspect crop) without publishing.
    """
    pv = await _get_variant_for_user(variant_id, str(user.id), db)
    if not pv.media_url:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Variant has no media_url to validate.")

    platform = str(pv.platform or "")
    original_url = str(pv.media_url)

    async def _run(url: str) -> dict[str, Any]:
        info = await probe_url(url)
        validate_for_platform(platform, info)
        return {
            "ok": True,
            "platform": platform,
            "media_url": url,
            "info": {
                "kind": info.kind,
                "bytes": info.bytes,
                "width": info.width,
                "height": info.height,
                "duration_seconds": info.duration_seconds,
                "format_name": info.format_name,
                "codec_name": info.codec_name,
            },
        }

    try:
        res = await _run(original_url)
        return {**res, "autofix_applied": False}
    except MediaValidationError as e:
        # Attempt Cloudinary auto-fix
        ms = MediaService()
        fixed = ms.resize_for_platform(original_url, platform, "video")
        if fixed.url != original_url:
            try:
                res2 = await _run(fixed.url)
                pv.media_url = fixed.url
                pv.metadata_json = {**(pv.metadata_json or {}), "media_autofix": True}
                pv.error_message = None
                db.add(pv)
                await db.commit()
                return {**res2, "autofix_applied": True, "original_media_url": original_url}
            except MediaValidationError:
                pass

        pv.error_message = f"Media validation failed: {e}"
        db.add(pv)
        await db.commit()
        return {
            "ok": False,
            "platform": platform,
            "media_url": original_url,
            "error": str(e),
            "autofix_applied": False,
        }


class ConfirmAssistedRequest(BaseModel):
    confirmed_at: datetime | None = None


@router.post("/assisted/{variant_id}/prepare")
async def assisted_prepare(
    variant_id: str,
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
):
    pv = await _get_variant_for_user(variant_id, str(user.id), db)
    publisher = AssistedPublisher()

    platform = (pv.platform or "").lower()
    if platform == "instagram":
        pkg = await publisher.prepare_instagram_assisted(variant_id, db)
        return pkg.model_dump()
    if platform == "linkedin":
        pkg = await publisher.prepare_linkedin_assisted(variant_id, db)
        return pkg.model_dump()

    raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Variant is not an assisted platform")


@router.post("/assisted/{variant_id}/confirm")
async def assisted_confirm_published(
    variant_id: str,
    payload: ConfirmAssistedRequest,
    db: AsyncSession = Depends(get_db),
    user: User = Depends(get_current_user),
):
    _ = await _get_variant_for_user(variant_id, str(user.id), db)
    publisher = AssistedPublisher()
    confirmed_at = payload.confirmed_at or datetime.now(timezone.utc)
    result = await publisher.mark_as_published(variant_id, db, confirmed_at=confirmed_at)
    return result


